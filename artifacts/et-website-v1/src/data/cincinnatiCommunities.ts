function makeCincinnatiConfig(input: CincyInput): CommunityConfig {
  const { slug, cityName, heroFile, heroAlt, heroPosition, heroZoom, geo, intro, overview,
          overviewSource, salesDOM, rentalsDOM, salesPrice, rentalsPrice,
          ownerPct, medianIncome, schools, nearby } = input;

  const renterPct = 100 - ownerPct;

  return {
    slug,
    cityName,
    regionName: "Cincinnati",
    stateName: "Ohio",
    urlPath: `/locations/cincinnati/${slug}`,

    seoTitle: `${cityName} Property Management & Property Services | EquityTeam`,
    seoDescription: `Professional property management in ${cityName}, Cincinnati, Ohio by EquityTeam — leasing, rent collection, maintenance, and owner reporting.`,

    heroImage: `${ORIGIN}/images/locations/heroes/${heroFile}`,
    heroImageAlt: heroAlt,
    ...(heroPosition ? { heroImagePosition: heroPosition } : {}),
    ...(heroZoom !== undefined ? { heroImageZoom: heroZoom } : {}),
    heroHeadline: `${cityName}, Ohio.`,
    heroSubheadline: "Property Management & Property Services",
    founderQuote: "We'll treat your property like it's our own.",
    founderName: "",

    stats: SHARED_STATS,

    introCopy: intro,

    serviceCopy: makeServiceCopy(cityName),

    forRent: {
      heading: `Looking to Rent in ${cityName}?`,
      subhead: `Browse current ${cityName} rentals managed by EquityTeam. Updated availability, photos, and online applications for prospective residents.`,
      href: "/for-rent",
      cta: "Browse Rentals",
    },

    areaOverview: {
      heading: `About ${cityName}`,
      paragraphs: overview,
      ...(overviewSource ? { source: overviewSource } : {}),
    },

    dataAccessedDate: "May 2026",

    marketInsightsSources: DEFAULT_SOURCES,

    marketInsights: [
      { icon: Clock, label: "Avg Days on Market", value: [`Sales: ${salesDOM}`, `Rentals: ${rentalsDOM}`] },
      { icon: House, label: "Active Inventory", value: ["Updated quarterly — contact us for current counts"] },
      { icon: Tag, label: "Housing Prices", value: [`Sales: ${salesPrice}`, `Rentals: ${rentalsPrice}`] },
      { icon: Users, label: "Owners vs Renters", value: [`~${ownerPct}% owner-occupied`, `~${renterPct}% renter-occupied`] },
      { icon: CurrencyDollar, label: "Median Household Income", value: medianIncome },
      { icon: GraduationCap, label: "Notable Schools", value: schools },
    ],

    testimonials: SHARED_TESTIMONIALS,

    faqs: buildLocationFaqs(cityName, LOCATION_FAQ_STATS[slug] ?? {
      medianHHI: medianIncome,
      renterPct: `${renterPct}%`,
      rent1BR: FALLBACK_FAQ_STATS.rent1BR,
      rent3BR: FALLBACK_FAQ_STATS.rent3BR,
    }),

    nearbyHeading: `Areas We Serve Near ${cityName}`,
    nearbyAreas: nearby.map((n) => {
      const href = CINCY_HREF[n.name];
      return href
        ? { name: n.name, href, coords: { lat: n.lat, lng: n.lng } }
        : { name: n.name, href: "#", coords: { lat: n.lat, lng: n.lng }, comingSoon: true as const };
    }),
    allAreasHref: "/areas-we-serve",
    allAreasLabel: "See all Cincinnati areas we serve",

    ctaHeadline: `Need help with a property in ${cityName}?`,
    ctaSubheadline: "",
    phone: "(513) 444-4010",
    phoneHref: "tel:+15134444010",

    business: {
      name: "EquityTeam Property Management",
      streetAddress: "11427 Reed Hartman Hwy",
      addressLocality: "Cincinnati",
      addressRegion: "OH",
      postalCode: "45241",
      telephone: "+15134444010",
      url: `${SITE_URL}/locations/cincinnati/${slug}`,
      serviceArea: `${cityName}, Cincinnati, Ohio`,
      geo,
    },
  };
}

